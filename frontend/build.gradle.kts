// The npm tasks deliberately do NOT declare `node_modules` as a Gradle output/input.
// `node_modules` holds tens of thousands of files; having Gradle fingerprint that tree for
// up-to-date checking thrashes the daemon's heap. Instead, npmInstall writes a tiny marker
// file as its output and is considered up-to-date only while both the marker and
// `node_modules` exist and package.json / package-lock.json are unchanged.

val npmInstallMarker = layout.buildDirectory.file("npm-install.marker")

/** The Vite dev server port (fixed: `strictPort` in vite.config.ts; the e2e tests expect it). */
val DEV_PORT = 5174

tasks.register<Exec>("npmInstall") {
    workingDir = projectDir
    commandLine("cmd", "/c", "npm", "install")
    inputs.file("package.json")
    inputs.file("package-lock.json")
    outputs.file(npmInstallMarker)
    // Re-run if node_modules was removed even though the marker survived.
    outputs.upToDateWhen { file("node_modules").isDirectory }
    doLast {
        val marker = npmInstallMarker.get().asFile
        marker.parentFile.mkdirs()
        marker.writeText("installed")
    }
}

tasks.register<Exec>("npmBuild") {
    dependsOn("npmInstall")
    workingDir = projectDir
    commandLine("cmd", "/c", "npm", "run", "build")
    // The Paraglide output in src/paraglide is generated by the build itself.
    inputs.files(fileTree("src") { exclude("paraglide/**") })
    inputs.file("vite.config.ts")
    inputs.file("tsconfig.json")
    inputs.file("package.json")
    inputs.dir("messages")
    inputs.dir("public")
    // Vite output.
    outputs.dir("dist")
}

tasks.register<Exec>("npmTest") {
    dependsOn("npmInstall")
    workingDir = projectDir
    commandLine("cmd", "/c", "npm", "test")
}

// The Vite dev server. Not an Exec task: stopping an Exec task kills only the `cmd` it started, and
// Windows leaves that process's children (npm → node/Vite) running, still holding port 5173. This task
// starts the process itself and, when Gradle cancels it (the IDE's stop button, Ctrl+C), ends the whole
// process tree. Should a server still be left over (e.g. the Gradle daemon itself was killed), run
// `npmDevStop`.
tasks.register("npmDev") {
    group = "frontend"
    description = "Run the Vite dev server on port $DEV_PORT (stopping the task stops the server)"
    dependsOn("npmInstall")
    val dir = projectDir
    doLast {
        val process = ProcessBuilder("cmd", "/c", "npm", "run", "dev")
            .directory(dir)
            .redirectErrorStream(true)
            .start()
        // Forward the server's output to the Gradle console (a daemon thread, so it never blocks the stop).
        val log = logger
        val pump = Thread {
            process.inputStream.bufferedReader().forEachLine { log.lifecycle(it) }
        }.apply { isDaemon = true }
        pump.start()
        try {
            val exit = process.waitFor()
            pump.join(2000)
            if (exit != 0) throw GradleException("The dev server exited with code $exit (port $DEV_PORT taken? run npmDevStop)")
        } finally {
            // Cancelling the task interrupts waitFor(); snapshot the tree first, then end children before the parent.
            val tree = process.descendants().toList()
            tree.forEach { it.destroyForcibly() }
            process.destroyForcibly()
        }
    }
}

// Free the dev-server port from a server left running (kills the process tree listening on it).
tasks.register<Exec>("npmDevStop") {
    group = "frontend"
    description = "Stop a Vite dev server still holding port $DEV_PORT"
    commandLine(
        "powershell", "-NoProfile", "-Command",
        "\$pids = Get-NetTCPConnection -LocalPort $DEV_PORT -State Listen -ErrorAction SilentlyContinue | " +
            "Select-Object -ExpandProperty OwningProcess -Unique; " +
            "if (\$pids) { foreach (\$p in \$pids) { taskkill /PID \$p /T /F } } " +
            "else { Write-Output 'Nothing is listening on port $DEV_PORT.' }",
    )
}

// `:frontend:build` builds the SPA; `:frontend:check` runs Vitest.
tasks.register("build") {
    dependsOn("npmBuild")
}

tasks.register("check") {
    dependsOn("npmTest")
}
